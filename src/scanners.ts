// ---- argv builders -------------------------------------------------------

export function resolveJobs(): number {
  return Math.max(1, os.availableParallelism?.() ?? os.cpus().length);
}

/**
 * Token → `ci` (diff-aware via SEMGREP_BASELINE_COMMIT env, which must be the merge-base).
 * No token → `scan` with `--baseline-commit`; `ci` is never claimed diff-aware without a token.
 * Both branches pass `--sarif` so stdout is SARIF.
 * No token uses `--config p/default`: `--config auto` is rejected with `--metrics=off`
 * ("Cannot create auto config when metrics are off"); `p/default` is the curated registry
 * pack that respects `--metrics=off`.
 */
export function semgrepArgv(o: { baselineSha: string; jobs: number; hasToken: boolean }): {
  argv: string[];
  env: { SEMGREP_BASELINE_COMMIT?: string };
} {
  if (o.hasToken) {
    return {
      argv: ["ci", "--sarif", "--metrics=off", "--jobs", String(o.jobs)],
      env: { SEMGREP_BASELINE_COMMIT: o.baselineSha },
    };
  }
  return {
    argv: [
      "scan",
      "--config",
      "p/default",
      "--sarif",
      "--metrics=off",
      "--jobs",
      String(o.jobs),
      "--baseline-commit",
      o.baselineSha,
    ],
    env: {},
  };
}

/** gitleaks writes SARIF to a file (`--report-path`), not to stdout. */
export function gitleaksArgv(dir: string, reportPath: string): string[] {
  return ["dir", dir, "--report-format", "sarif", "--report-path", reportPath];
}

export function trivyArgv(target: string): string[] {
  return ["fs", "--format", "sarif", "--severity", "HIGH,CRITICAL", target];
}

/** SBOM is generated by a scan (`fs`), never by the `sbom` subcommand (which consumes an SBOM). */
export function sbomArgv(target: string): string[] {
  return ["fs", "--format", "cyclonedx", target];
}

/** osv-scanner v2 CLI. The v1 `scan source --lockfile=` form does not exist in v2. */
export function osvArgv(lockfile: string): string[] {
  return ["scan", "-L", lockfile, "--format", "sarif"];
}

// ---- SARIF gating --------------------------------------------------------

/**
 * Same-repo check per event:
 * - pull_request: payload.pullHeadRepo (from the event path) must equal repo.
 * - workflow_run: prMeta.head_repo_full_name (from the pr-meta artifact) must equal repo.
 */
export function isSameRepo(
  event: string,
  payload: { pullHeadRepo?: string },
  prMeta?: PrMeta,
  repo?: string,
): boolean {
  if (!repo) return false;
  if (event === "pull_request") return payload.pullHeadRepo === repo;
  if (event === "workflow_run") return prMeta?.head_repo_full_name === repo;
  return false;
}

export function shouldUploadSarif(o: {
  isSameRepo: boolean;
  hasPermission: boolean;
  codeScanningEnabled: boolean;
}): boolean {
  return o.isSameRepo && o.hasPermission && o.codeScanningEnabled;
}

// ---- parsing -------------------------------------------------------------

type Obj = Record<string, unknown>;

function isObj(v: unknown): v is Obj {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/**
 * Normalize a SARIF artifactLocation URI to a repo-relative path. Docker scanners mount the
 * repo at `/src`, so their SARIF reports absolute `/src/<rel>` paths (or `file:///src/<rel>`);
 * `unsafePath()` rejects absolute paths and the finding degrades to a repository-level note.
 * Only the known container mount (`/src/`, optionally behind a `file://` scheme) is stripped;
 * repo-relative paths and other absolute paths are returned untouched.
 */
function normalizeArtifactUri(uri: string): string {
  const path = uri.startsWith("file://") ? uri.slice("file://".length) : uri;
  if (path.startsWith("/src/")) return path.slice("/src/".length);
  return uri;
}

function firstPhysicalLocation(locations: unknown): { file: string; line?: number } {
  if (!Array.isArray(locations) || !isObj(locations[0])) return { file: "" };
  const phys = locations[0].physicalLocation;
  if (!isObj(phys)) return { file: "" };
  const art = isObj(phys.artifactLocation) ? phys.artifactLocation : undefined;
  const region = isObj(phys.region) ? phys.region : undefined;
  const file = typeof art?.uri === "string" ? normalizeArtifactUri(art.uri) : "";
  const line = typeof region?.startLine === "number" ? region.startLine : undefined;
  return { file, line };
}

/** SARIF 2.1.0 level → severity. A missing level defaults to "warning" per the spec. */
function severityOf(level: unknown): Finding["severity"] {
  if (level === undefined) return "warning";
  if (level === "error") return "high";
  if (level === "note" || level === "none") return "info";
  return "warning";
}

/**
 * Parse a SARIF 2.1.0 log into Findings. Returns `undefined` when the text is not
 * a SARIF log (invalid JSON or no `runs` array) so the caller can fail loudly.
 * Malformed runs/results/locations are skipped, never thrown on.
 */
export function parseSarif(text: string): Finding[] | undefined {
  let log: unknown;
  try {
    log = JSON.parse(text);
  } catch {
    return undefined;
  }
  if (!isObj(log) || !Array.isArray(log.runs)) return undefined;

  const out: Finding[] = [];
  for (const run of log.runs) {
    if (!isObj(run) || !Array.isArray(run.results)) continue;
    for (const res of run.results) {
      if (!isObj(res)) continue;
      const { file, line } = firstPhysicalLocation(res.locations);
      const msg = isObj(res.message) ? res.message.text : undefined;
      out.push({
        severity: severityOf(res.level),
        file,
        line,
        rule: typeof res.ruleId === "string" ? res.ruleId : "unknown",
        message: typeof msg === "string" ? msg : "scanner finding",
      });
    }
  }
  return out;
}

// ---- execution -----------------------------------------------------------

/** Per-tool wall-clock budget. A tool that exceeds it is killed and reported as a warning. */
export const TOOL_TIMEOUT_MS = 600_000;

interface Exec {
  missing: boolean; // ENOENT: binary not on PATH
  code: number | null; // 0 on success; numeric exit code otherwise (null if killed by signal)
  stdout: string;
  timedOut: boolean; // killed by the timeout
}

/** Runs one tool. Exported for tests (the timeout parameter is the seam). */
export function runExec(
  file: string,
  args: string[],
  cwd: string,
  env?: NodeJS.ProcessEnv,
  timeoutMs: number = TOOL_TIMEOUT_MS,
): Promise<Exec> {
  return new Promise((resolve) => {
    execFile(
      file,
      args,
      { cwd, env: { ...process.env, ...env }, maxBuffer: MAX_BUFFER, timeout: timeoutMs },
      (err, stdout) => {
        if (!err) return resolve({ missing: false, code: 0, stdout: String(stdout), timedOut: false });
        const e = err as NodeJS.ErrnoException & { killed?: boolean };
        if (e.code === "ENOENT") return resolve({ missing: true, code: null, stdout: "", timedOut: false });
        // execFile sets `killed` when its timeout fires.
        const timedOut = e.killed === true;
        // Non-zero exit (scanners exit 1 when findings exist): keep stdout, which may hold SARIF.
        const code = typeof e.code === "number" ? e.code : null;
        resolve({ missing: false, code, stdout: stdout ? String(stdout) : "", timedOut });
      },
    );
  });
}

function warning(rule: string, message: string): Finding {
  return { severity: "warning", file: "", rule, message };
}

/**
 * Invocation health from a SARIF log (F08). Re-parses `stdout` without touching
 * `parseSarif`. Returns `true` when any `runs[].invocations[]` entry reports
 * `executionSuccessful === false` or carries an error-level
 * `toolExecutionNotifications` entry, `false` when invocation info is present
 * and all successful, and `undefined` when the SARIF carries no invocation
 * info at all (so the caller falls back to the exit-code rule).
 */
function invocationFailed(stdout: string): boolean | undefined {
  let log: unknown;
  try {
    log = JSON.parse(stdout);
  } catch {
    return undefined;
  }
  if (!isObj(log) || !Array.isArray(log.runs)) return undefined;
  let seen = false;
  for (const run of log.runs) {
    if (!isObj(run) || !Array.isArray(run.invocations)) continue;
    for (const inv of run.invocations) {
      if (!isObj(inv)) continue;
      seen = true;
      if (inv.executionSuccessful === false) return true;
      if (Array.isArray(inv.toolExecutionNotifications)) {
        for (const n of inv.toolExecutionNotifications) {
          if (isObj(n) && n.level === "error") return true;
        }
      }
    }
  }
  return seen ? false : undefined;
}

/**
 * Exit codes that mean "findings present", keyed by scanner `label` (not `tool`:
 * `tool` is `"docker"` for both trivy and osv). The osv label carries the
 * lockfile in parentheses (`osv-scanner (<lock>)`), so it matches by prefix.
 * Trivy's argv has no `--exit-code`, so its findings exit is 0 and any nonzero
 * is an error; semgrep exits 1 on findings; osv-scanner exits 1 on findings.
 */
function findingsExitCodes(label: string): number[] {
  if (label === "semgrep") return [1];
  if (label === "osv-scanner" || label.startsWith("osv-scanner ")) return [1];
  return [];
}

/**
 * Interpret a scanner whose SARIF arrives on stdout. Fail-open: a non-zero exit (or
 * any exit) with empty/unparseable stdout is a `scanner-failed` warning, never a clean pass.
 * The `maxBytes` byte check runs before parsing (after the missing/timedOut guards).
 * The timeout message names the actual `timeoutMs` budget the tool ran under.
 * Parsed findings are always kept; a failed invocation appends a `scanner-failed`
 * warning, never substituted. Explicit invocation success wins over a contradictory
 * exit code; code 0 with no invocation info stays quiet.
 */
export function fromStdout(tool: string, label: string, r: Exec, timeoutMs: number = TOOL_TIMEOUT_MS, maxBytes: number = DEFAULT_MAX_ARTIFACT_BYTES): Finding[] {
  if (r.missing) return [warning("scanner-missing", `${label} unavailable: ${tool} not found`)];
  if (r.timedOut) return [warning("scanner-failed", `${label} timed out after ${timeoutMs / 1000}s`)];
  const over = byteCheck(r.stdout, maxBytes, label);
  if (over !== undefined) return over;
  const parsed = r.stdout.trim() ? parseSarif(r.stdout) : undefined;
  if (!parsed) {
    return [warning("scanner-failed", `${label} exited ${r.code ?? "abnormally"} without parseable SARIF`)];
  }
  const health = invocationFailed(r.stdout);
  if (health === true) {
    return [...parsed, warning("scanner-failed", `${label} reported an unsuccessful run`)];
  }
  if (health === false) return parsed;
  if (r.code === 0) return parsed;
  if (r.code === null || !findingsExitCodes(label).includes(r.code)) {
    return [...parsed, warning("scanner-failed", `${label} reported an unsuccessful run`)];
  }
  return parsed;
}

/**
 * Docker invocation for digest-pinned images. `extraMounts` are `host:container` pairs.
 * Known limitation: a `:` in `dir` breaks the `-v` volume argument. The docker path is
 * not used on Windows runners in v1.
 */
function dockerArgs(
  dir: string,
  image: string,
  digest: string,
  args: string[],
  extraMounts: string[] = [],
): string[] {
  const mounts = [`${dir}:/src`, ...extraMounts].flatMap((m) => ["-v", m]);
  return ["run", "--rm", ...mounts, "-w", "/src", `${image}@${digest}`, ...args];
}

export interface ScannerResult {
  findings: Finding[];
  /** Path of the CycloneDX SBOM when `sbom` was requested and generated. */
  sbomPath?: string;
}

/**
 * Runs the L1 scanners. Never throws: a missing binary becomes `scanner-missing`,
 * an unusable scanner result becomes `scanner-failed` (fail-open warning).
 * Optional: `hasSemgrepToken`, `jobs`, `sbom` (default false), `lockfiles` (OSV targets),
 * `outDir` (parent for the SBOM's mkdtemp dir; defaults to `os.tmpdir()`),
 * `timeoutMs` (per-tool wall-clock budget; defaults to `TOOL_TIMEOUT_MS`, threaded to every
 * tool invocation and to its timeout message).
 * `maxArtifactBytes` (read cap for scanner artifacts; defaults to `DEFAULT_MAX_ARTIFACT_BYTES`).
 * Lifecycle: `sbomPath` is returned for upload; the caller (Task 12) owns the file and its
 * temp dir. runScanners does NOT delete the SBOM.
 * Semgrep runs the PyPI binary; trivy/osv/gitleaks run from digest-pinned docker images.
 */
export async function runScanners(o: {
  dir: string;
  baselineSha: string;
  hasSemgrepToken?: boolean;
  jobs?: number;
  sbom?: boolean;
  lockfiles?: string[];
  outDir?: string;
  timeoutMs?: number;
  maxArtifactBytes?: number;
}): Promise<ScannerResult> {
  const findings: Finding[] = [];
  const jobs = o.jobs ?? resolveJobs();
  const dir = resolvePath(o.dir);
  const timeoutMs = o.timeoutMs ?? TOOL_TIMEOUT_MS;
  const maxArtifactBytes = o.maxArtifactBytes ?? DEFAULT_MAX_ARTIFACT_BYTES;

  // semgrep (binary, not docker)
  const sg = semgrepArgv({ baselineSha: o.baselineSha, jobs, hasToken: !!o.hasSemgrepToken });
  findings.push(...fromStdout("semgrep", "semgrep", await runExec("semgrep", sg.argv, dir, sg.env, timeoutMs), timeoutMs, maxArtifactBytes));

  // trivy (docker image pinned by digest)
  const tv = await runExec("docker", dockerArgs(dir, TRIVY_IMAGE, TRIVY_DIGEST, trivyArgv(".")), dir, undefined, timeoutMs);
  findings.push(...fromStdout("docker", "trivy", tv, timeoutMs, maxArtifactBytes));

  // gitleaks (docker image pinned by digest; SARIF goes to a report file in a temp dir)
  findings.push(...(await runGitleaks(dir, timeoutMs, maxArtifactBytes)));

  // osv-scanner (docker image pinned by digest), one run per lockfile
  for (const lock of o.lockfiles ?? []) {
    const osv = await runExec("docker", dockerArgs(dir, OSV_IMAGE, OSV_DIGEST, osvArgv(lock)), dir, undefined, timeoutMs);
    findings.push(...fromStdout("docker", `osv-scanner (${lock})`, osv, timeoutMs, maxArtifactBytes));
  }

  // SBOM (trivy fs --format cyclonedx). Written under a unique mkdtemp dir inside outDir.
  let sbomPath: string | undefined;
  if (o.sbom) {
    const sb = await runExec("docker", dockerArgs(dir, TRIVY_IMAGE, TRIVY_DIGEST, sbomArgv(".")), dir, undefined, timeoutMs);
    if (sb.missing) {
      findings.push(warning("scanner-missing", "sbom unavailable: docker not found"));
    } else {
      const over = byteCheck(sb.stdout, maxArtifactBytes, "sbom");
      if (over !== undefined) {
        findings.push(...over);
      } else if (!isCycloneDx(sb.stdout)) {
        // The exit code is not decisive: a valid CycloneDX document is accepted even on non-zero
        // exit (scanners exit non-zero when they report findings), matching the SARIF rule.
        findings.push(warning("scanner-failed", `sbom exited ${sb.code ?? "abnormally"} without a CycloneDX document`));
      } else {
        let sbomDir: string | undefined;
        try {
          sbomDir = await mkdtemp(join(o.outDir ?? os.tmpdir(), "sbom-"));
          const out = join(sbomDir, "sbom.cdx.json");
          await writeFile(out, sb.stdout, "utf8");
          sbomPath = out;
        } catch (e) {
          // A failed write must not leave a half-created dir behind: remove it best-effort.
          if (sbomDir) await rm(sbomDir, { recursive: true, force: true }).catch(() => undefined);
          findings.push(warning("sbom-write", `could not write SBOM: ${(e as Error).message}`));
        }
      }
    }
  }

  return { findings, sbomPath };
}

/** True when `text` is a CycloneDX document: a JSON object with bomFormat "CycloneDX". */
function isCycloneDx(text: string): boolean {
  try {
    const parsed: unknown = JSON.parse(text);
    return isObj(parsed) && parsed.bomFormat === "CycloneDX";
  } catch {
    return false;
  }
}

/**
 * gitleaks writes its SARIF report to a file. The report lives in a temp dir mounted at
 * /out inside the container and is removed afterwards (best-effort). gitleaks exits 0
 * when clean and may not create the report; exit 0 with no report is therefore clean.
 * A temp-dir failure is a `scanner-failed` warning, never a throw.
 */
async function runGitleaks(dir: string, timeoutMs: number = TOOL_TIMEOUT_MS, maxBytes: number = DEFAULT_MAX_ARTIFACT_BYTES): Promise<Finding[]> {
  let reportDir: string;
  try {
    reportDir = await mkdtemp(join(os.tmpdir(), "gitleaks-"));
  } catch (e) {
    return [warning("scanner-failed", `gitleaks temp dir unavailable: ${(e as Error).message}`)];
  }
  const hostReport = join(reportDir, "report.sarif");
  try {
    const gl = await runExec(
      "docker",
      dockerArgs(dir, GITLEAKS_IMAGE, GITLEAKS_DIGEST, gitleaksArgv("/src", "/out/report.sarif"), [
        `${reportDir}:/out`,
      ]),
      dir,
      undefined,
      timeoutMs,
    );
    if (gl.missing) return [warning("scanner-missing", "gitleaks unavailable: docker not found")];
    if (gl.timedOut) return [warning("scanner-failed", `gitleaks timed out after ${timeoutMs / 1000}s`)];
    let text: string | undefined;
    try {
      const capped = readCappedFileSync(hostReport, maxBytes);
      if (!capped.ok) {
        return [warning("scanner-failed", oversizeMessage("gitleaks", maxBytes))];
      }
      text = capped.text;
    } catch {
      text = undefined;
    }
    if (text === undefined) {
      return gl.code === 0 ? [] : [warning("scanner-failed", `gitleaks exited ${gl.code ?? "abnormally"} with no report`)];
    }
    const parsed = parseSarif(text);
    if (!parsed) return [warning("scanner-failed", "gitleaks report is not parseable SARIF")];
    // Exit codes do not apply here (this path parses a report file, not a process
    // result), but invocation health still does when the SARIF carries it.
    if (invocationFailed(text) === true) {
      return [...parsed, warning("scanner-failed", "gitleaks reported an unsuccessful run")];
    }
    return parsed;
  } finally {
    await rm(reportDir, { recursive: true, force: true }).catch(() => undefined);
  }
}
